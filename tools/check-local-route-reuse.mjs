import assert from 'node:assert/strict';
import {TerrainNavigator} from '../campaign/navigation.js';
import {sharedRouteTree} from '../campaign/shared-route-tree.js';
const finish=it=>{let r;do{r=it.next();}while(!r.done);return r.value;};
const field={extent:4096,half:2048,cellMetres:32,heightAt:()=>0,gradientAt:()=>({x:0,y:0})};
const nav=new TerrainNavigator(field),wall={id:'wall',x:0,y:0,halfWidth:20,halfDepth:55,hp:1};nav.rebuild([wall]);
const context=nav.createSearchContext(),from={x:-800,y:0,kind:'bukhanka'},to={x:800,y:0};
const path=[-600,-400,-200,0,200,400,600].map(x=>({x,y:-128})).concat(to);
context.rememberCorridor(from,to,path);
assert(finish(context.reuseCorridor(from,to,{occupancyKey:''})));
assert.equal(context.corridorSegmentChecks??0,0);
const changed={id:'beside-route',x:0,y:-180,halfWidth:8,halfDepth:8,hp:1};
nav.rebuild([wall,changed]);
let copied=0;const set=context.occupied.set.bind(context.occupied);
context.occupied.set=(data,offset)=>{copied+=data.length;return set(data,offset);};
context.refreshContext();assert(copied>0&&copied<1024,'Only changed occupancy tiles are copied');
assert.deepEqual([...context.occupied],[...nav.occupied]);
const reused=finish(context.reuseCorridor(from,to,{occupancyKey:''}));assert(reused);
assert(context.corridorSegmentChecks>0&&context.corridorSegmentChecks<path.length-2,'Only changed interior segments are checked');
const checks=context.corridorSegmentChecks;context.refreshContext();const previousCopied=copied;
assert(finish(context.reuseCorridor(from,to,{occupancyKey:''})));assert.equal(context.corridorSegmentChecks,checks);
context.refreshContext();assert.equal(copied,previousCopied,'Unchanged snapshots do not recopy occupancy');
// Several structural updates can occur while a context is parked in a pool.
const far={id:'far',x:800,y:800,halfWidth:8,halfDepth:8,hp:1};
nav.rebuild([wall,changed,far]);nav.rebuild([wall,far]);context.refreshContext();
assert.deepEqual([...context.occupied],[...nav.occupied]);
const blocked={...changed,y:-128};nav.rebuild([wall,blocked,far]);context.refreshContext();
assert.equal(finish(context.reuseCorridor(from,to,{occupancyKey:''})),null,'An actually blocked retained edge cannot be reused');

const fresh=new TerrainNavigator(field);fresh.rebuild([]);
const goal={x:256,y:0},tree=sharedRouteTree(fresh,goal,false);assert(finish(tree.route({x:-256,y:0})));
const a={x:-448,y:1024},b={x:448,y:1024};assert(tree.clearSegment(a,b));
const chordObstacle={id:'chord',x:0,y:1024,halfWidth:20,halfDepth:20,hp:1};fresh.rebuild([chordObstacle]);
assert(sharedRouteTree(fresh,goal,false)===tree,'An unrelated smoothing chord does not erase settled nodes');
assert.equal(tree.clearSegment(a,b),false,'The changed chord is checked again');
fresh.rebuild([]);assert(tree.clearSegment(a,b),'Removal invalidates a cached rejection too');
const start={x:-128,y:0},end={x:128,y:0};const expected=tree.travelCost(start,end);assert(tree.clearSegment(start,end));
const other=fresh.createSearchContext(),next=sharedRouteTree(other,{x:400,y:100},false);
assert.equal(next.travelCost(start,end),expected);assert.equal(next.costCacheHits,1,'Another order/context reuses directed segment costs');
assert(next.clearSegment(start,end));assert.equal(next.clearanceCacheHits,1);
const oldCosts=next.segmentCosts;
fresh.field.localRoads=[{id:'new-road',width:20,points:[start,end]}];fresh.rebuild([]);other.refreshContext();
assert(!next.valid(),'Road edits invalidate the old cost profile');
assert.notEqual(sharedRouteTree(other,{x:400,y:100},false).segmentCosts,oldCosts);
console.log(JSON.stringify({passed:true,interiorSegmentChecks:checks,totalSegments:path.length,copiedCells:copied,sharedAcrossOrders:true}));
