import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {progressMission} from './check-navigation-public-progress.mjs';
import {vehicleClearance} from '../campaign/vehicle-collision.js';
import {corridorReservationActive} from '../campaign/traffic-corridor.js';
const fixture=JSON.parse(fs.readFileSync('tools/fixtures/navigation-terminal-arrival.json'));
const scene=snapshot=>{const m=progressMission();m.load(structuredClone(snapshot));m.state.bounds=[0,0,127,127];m.rebuildNavigation();return m;};
const files=['mission','traffic-start','traffic-arrival-route','traffic-joint','traffic-corridor','vehicle-motion','vehicle-collision'];
const hashes=()=>Object.fromEntries(files.map(f=>[f,createHash('sha256').update(fs.readFileSync('campaign/'+f+'.js')).digest('hex')]));
const sourceHashes=hashes(),results=[],stages={};
function run(m,capture=false){
const units=m.state.units,goals=new Map(units.filter(u=>u.routeOrder?.destination).map(u=>[u.id,structuredClone(u.routeOrder.destination)]));
const hp=new Map(units.map(u=>[u.id,u.hp])),start=m.state.time,wall=performance.now(),contacts=[];
const done=u=>!u.task&&!u.path.length&&!u.pendingOrder&&!u.detour&&!u.yieldReturn&&!u.jointTraffic;
let minGap=Infinity,maxWait=0,maxAdvanceMs=0,observed=0;const tick=m.continueTick,collision=m.vehicleCollision.bind(m);
m.vehicleCollision=(u,s,b)=>{if(b.size)contacts.push({id:u.id,time:m.state.time,blockers:[...b].map(v=>v.id)});return collision(u,s,b);};
m.continueTick=function(...args){const pending=this.pendingTick,result=tick.apply(this,args);if(pending&&!this.pendingTick){
 observed++;
 for(const u of units){assert.equal(u.hp,hp.get(u.id));if(goals.has(u.id))assert.deepEqual(u.routeOrder.destination,goals.get(u.id));
  if(u.navigation?.stoppedSince!=null)maxWait=Math.max(maxWait,this.state.time-Math.max(start,u.navigation.stoppedSince));}
 for(let a=0;a<units.length;a++)for(let b=0;b<a;b++)minGap=Math.min(minGap,vehicleClearance(units[a],units[b],m.config.worldScale,m.field));
 if(capture&&!stages.approach&&this.entity('u208').detour?.preciseArrival)stages.approach=JSON.parse(this.save());
}return result;};
while((m.pendingTick||units.some(u=>!done(u)))&&m.state.time-start<60&&performance.now()-wall<90000){
 const before=performance.now();m.advance(1/80,{budgetMs:5});maxAdvanceMs=Math.max(maxAdvanceMs,performance.now()-before);m.effects=[];
}
const result={seconds:m.state.time-start,wallSeconds:(performance.now()-wall)/1000,arrived:units.filter(u=>goals.has(u.id)&&done(u)).length,
 total:goals.size,minGap,contacts,maxWait,maxAdvanceMs,observed,
 unfinished:units.filter(u=>!done(u)).map(u=>({id:u.id,task:u.task,path:u.path,navigation:u.navigation}))};
result.passed=result.arrived===result.total&&minGap>0&&!contacts.length&&maxWait<=30;
results.push(result);
fs.writeFileSync('campaign/reports/terminal-arrival.json',JSON.stringify({passed:false,result,results,stages,final:JSON.parse(m.save()),sourceHashes,sourcesUnchanged:JSON.stringify(sourceHashes)===JSON.stringify(hashes())},null,2));
console.log(JSON.stringify(result));assert(result.passed,'The frozen 49/50 command and every borrowed place must finish without a new click');
for(const [id,goal] of goals){const u=m.entity(id);assert(Math.hypot(u.x-goal.x,u.y-goal.y)<2.01);}
assert(maxAdvanceMs<250,'Terminal planning must respect the yielding simulation work budget');
}
run(scene(fixture),true);
assert(stages.approach,'Capture an actual precise approach generated by the controller');
run(scene(stages.approach));
// A live replacement must revoke the compiled old approach and its reserved
// swept space immediately, including after loading a partly executed route.
for(const replacement of ['stop','move']){
 const m=scene(stages.approach),u=m.entity('u208'),before={x:u.x,y:u.y},corridor=u.detour.reservedCorridor;
 if(replacement==='stop')assert(m.stop([u.id],{expandGroup:false}).ok);
 else assert(m.submitOrder([u.id],'move',{x:-300,y:500}).ok);
 assert(!corridorReservationActive(m,{id:'outside',owner:u.owner},u,corridor),'The previous terminal approach loses its reservation immediately');
 if(replacement==='stop'){
  for(let i=0;i<10;i++)m.tick(.1);
  assert.deepEqual({x:u.x,y:u.y},before,'Stop cannot execute another piece of the old approach');
  assert(!u.task&&!u.path.length&&!u.routeOrder&&!u.detour&&!u.yieldReturn&&!u.jointTraffic);
 }else{
  for(let i=0;i<20000&&u.pendingOrder;i++)m.advance(1/80,{budgetMs:5});
  assert(!u.pendingOrder);assert.deepEqual(u.routeOrder.request,{x:-300,y:500});
 }
 console.log(JSON.stringify({passed:true,replacement}));
}
assert.deepEqual(hashes(),sourceHashes,'Sources must remain unchanged for the whole check');
const report=JSON.parse(fs.readFileSync('campaign/reports/terminal-arrival.json'));
Object.assign(report,{passed:true,replacementChecks:['stop','move']});
fs.writeFileSync('campaign/reports/terminal-arrival.json',JSON.stringify(report,null,2));
