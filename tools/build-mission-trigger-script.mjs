function register(line, clip, relativeBase = '') {
  const file = clip?.file ? path.resolve(base, relativeBase, clip.file) : null;
  const exists = !!file && fs.existsSync(file);
  if (exists && clip.sha256) assert.equal(createHash('sha256').update(fs.readFileSync(file)).digest('hex'), clip.sha256, line.id);
  const source = !exists ? 'missing' : clip.origin === 'user-recording' ? 'user' : 'temporary';
  cues.set(line.id, {...line, source, status:{user:'ЕСТЬ — ТВОЯ',temporary:'ЕСТЬ — ВРЕМЕННАЯ',missing:'НЕТ'}[source],
    audioFile:exists ? path.relative(root, file).replaceAll('\\', '/') : null});
}
for (const line of [...story.dialogue, ...story.barks]) {
  const clip = audio.clips[line.id];
  if (overrides.clips[line.id]) {
    assert.equal(clip?.origin, 'user-recording', line.id);
    assert.equal(clip.file, overrides.clips[line.id].file, line.id);
    assert.equal(line.text, overrides.clips[line.id].text, line.id);
  }
  register(line, clip);
}
