registerHooks({resolve(s,c,next){return s==='three'?{url:new URL('../demo/vendor/three.module.js',import.meta.url).href,shortCircuit:true}:next(s,c);}});
const {PoseBatch}=await import('../campaign/vehicle-layer.js');
const json=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const config=json('assets/campaign/alpha/mission01/gameplay.json');
const m=new Mission(config,createHeightfield(json('assets/maps/alpha/heightfield.json')));
const parts=config.units.builder.components;
assert.equal(vehiclePaint(m.state.units.find(u=>u.kind==='builder')).id,'gray');
assert.equal(vehiclePaint({kind:'bukhanka'}).id,'olive');
assert.equal(vehiclePaint({components:parts,paint:'#ff00ff'}).id,'gray','Arbitrary RGB is never accepted');
assert.equal(projectAssemblyKey({components:parts}),projectAssemblyKey({components:parts,paint:'gray'}));
const a=m.saveDesign('Серый строитель',parts),b=m.saveDesign('Песочный строитель',parts,'sand');
assert(a.ok&&b.ok);assert.equal(m.factoryProjects().filter(p=>p.kind==='builder').length,2,'Paint variants coexist');
const start=m.field.gridToWorld(config.startGrid);
const factory=m.addStructure('factory','rai',{x:start.x+170,y:start.y+100},{completed:true,progress:1});
m.rebuildNavigation();m.state.energy=2000;
assert(m.produce(factory.id,b.id).ok);
assert(m.saveDesign('Песочный II',parts,'sand').ok);
assert.equal(factory.queue[0].paint,'sand','Queued order keeps its paint after project replacement');
const originalQueue=factory.queue[0];
m.load(m.save());
const loadedFactory=m.entity(factory.id);
assert.deepEqual(loadedFactory.queue[0],originalQueue);
assert(m.spawnProducedVehicle(loadedFactory,loadedFactory.queue[0],config.buildings.factory),'Real factory exit produces the queued vehicle');
let produced=m.state.units.at(-1);
assert.equal(produced.paint,'sand');assert.equal(produced.kind,'builder');
assert.equal(produced.maxHp,config.units.builder.hp,'Paint does not affect vehicle stats');
m.load(m.save());assert.equal(m.entity(produced.id).paint,'sand');
assert(m.produce(factory.id,a.id).ok);assert.equal(m.entity(factory.id).queue[0].paint,'gray');
// Legacy designs, queued orders and existing units have no paint field.
for(const project of m.state.designs)delete project.paint;
for(const unit of m.state.units)delete unit.paint;
for(const job of m.entity(factory.id).queue)delete job.paint;
m.load(m.save());
assert.equal(vehiclePaint(m.factoryProjects().find(p=>p.kind==='builder')).id,'gray');
m.state.units=m.state.units.filter(u=>u.id!==produced.id);m.rebuildNavigation();
assert(m.spawnProducedVehicle(m.entity(factory.id),m.entity(factory.id).queue[0],config.buildings.factory));
assert.equal(m.state.units.at(-1).paint,'gray');

const prototype=new T.Group(),paintMaterial=new T.MeshStandardMaterial({color:'#5c644c'});
paintMaterial.name='paint_olive';
for(const material of [paintMaterial,paintMaterial,new T.MeshStandardMaterial({color:'#21383e'}),new T.MeshStandardMaterial({color:'#171b19'})])prototype.add(new T.Mesh(new T.BoxGeometry(),material));
const snapshot=prototype.children.map(n=>n.material.color.toArray());
const preview=prototype.clone(true),release=paintVehicleModel(preview,vehiclePaint({paint:'sand'}));
assert.notEqual(preview.children[0].material,paintMaterial);
assert.equal(preview.children[0].material,preview.children[1].material,'Shared painted pieces reuse one cloned finish');
assert.deepEqual(prototype.children.map(n=>n.material.color.toArray()),snapshot,'Preview never recolours the shared GLB');
assert.equal(preview.children[2].material,prototype.children[2].material,'Glass is untouched');
let disposed=0;preview.children[0].material.addEventListener('dispose',()=>disposed++);release();assert.equal(disposed,1);
const damage={prepare:n=>({geometry:n.geometry,dynamic:false,bind:n.matrixWorld.clone(),linear:new T.Matrix3(),inverseLinear:new T.Matrix3()}),trackGeometry(){},attach(){}};
const batch=new PoseBatch(T,new T.Group(),prototype,2,damage,'body',0,{paintable:true}),matrix=new T.Matrix4(),white=new T.Color(0xffffff);
function draw(paints){batch.begin();for(const p of paints)batch.add(matrix,white,{},undefined,null,vehiclePaintTint(T,p));batch.end();
 for(const [i,p] of paints.entries())for(const part of batch.parts){const color=new T.Color();part.mesh.getColorAt(i,color);const expected=part.painted?vehiclePaintTint(T,p):white;assert.deepEqual(color.toArray(),expected.toArray().map(Math.fround));}}
draw(VEHICLE_PAINTS);draw(VEHICLE_PAINTS.toReversed());draw([VEHICLE_PAINTS[1],VEHICLE_PAINTS[0]]);
const version=batch.paintAttribute.version;draw([VEHICLE_PAINTS[1],VEHICLE_PAINTS[0]]);assert.equal(batch.paintAttribute.version,version);
const pool=createDamageDebris(T,new T.Scene(),{heightAt:()=>0},1),burned=createDamageState();burned.burn=.5;
prototype.updateMatrixWorld(true);
const bindings=prototype.children.slice(0,2).map(n=>prepareDamageGeometry(T,n,'weapon'));
assert(pool.spawn(bindings,9,burned,new T.Matrix4(),[1,0,0],20,null,{kind:'builder'}));
const grayBurned=new T.Color(vehiclePaint({kind:'builder'}).color).multiplyScalar(.85);
pool.root.children[0].traverse(n=>{if(n.isMesh)assert(n.material.color.toArray().every((v,i)=>Math.abs(v-grayBurned.toArray()[i])<1e-8),'Detached pieces retain paint and fire darkening');});
assert.deepEqual(paintMaterial.color.toArray(),snapshot[0],'Debris cannot recolour the shared prototype');pool.reset();
// Check every shipped LOD agrees with the tint's reference colour.
for(const id of ['C01','B01'])for(const lod of [0,1,2]){
 const bytes=fs.readFileSync(`assets/vehicles/${id}/${id}-lod${lod}.glb`),gltf=JSON.parse(bytes.subarray(20,20+bytes.readUInt32LE(12)));
 const paint=gltf.materials.find(mat=>mat.name==='paint_olive');assert(paint);
 paint.pbrMetallicRoughness.baseColorFactor.slice(0,3).forEach((v,i)=>assert(Math.abs(v-paintMaterial.color.toArray()[i])<1e-8));
}
console.log('PASS: defaults, curated palette, project variants, queue snapshot, production, saves/legacy saves, preview isolation, paint-only instancing, growth/repacking, painted debris, all LODs');
