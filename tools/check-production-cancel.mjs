import fs from 'node:fs';
import assert from 'node:assert/strict';
import {Mission} from '../campaign/mission.js';
import {createHeightfield} from '../demo/map-route.js';
const json=path=>JSON.parse(fs.readFileSync(path,'utf8'));
const config=json('assets/campaign/alpha/mission01/gameplay.json');
const m=new Mission(config,createHeightfield(json('assets/maps/alpha/heightfield.json')));
const factory=m.addStructure('factory','rai',{x:0,y:0},{completed:true,progress:1});
m.state.energy=2000;
for(const kind of ['bukhanka','builder','bukhanka'])assert(m.produce(factory.id,kind).ok);
factory.queue[0].progress=.4;
let energy=m.state.energy;
assert(m.cancelProduction(factory.id,'bukhanka').ok);
assert.equal(m.state.energy,energy+130);
assert.equal(factory.queue[0].progress,.4,'Cancel the last matching job before the running job');
energy=m.state.energy;
factory.exitBlocked=true;factory.exitRetryAt=100;
assert(m.cancelProduction(factory.id,'bukhanka').ok);
assert.equal(m.state.energy,energy+130*.6);
assert.equal(factory.queue[0].kind,'builder');
assert.equal(factory.queue[0].progress,0);
assert.equal(factory.exitBlocked,undefined);
assert.equal(factory.exitRetryAt,undefined);
energy=m.state.energy;
assert(!m.cancelProduction(factory.id,'bukhanka').ok);
assert.equal(m.state.energy,energy,'Repeated cancellation cannot duplicate the refund');
factory.owner='scavs';assert(!m.cancelProduction(factory.id,'builder').ok);
factory.owner='rai';factory.hp=0;assert(!m.cancelProduction(factory.id,'builder').ok);
factory.hp=factory.maxHp;
m.saveDesign('Новый строитель',config.units.builder.components);
const replacement=m.factoryProjects().find(p=>p.kind==='builder');
m.load(m.save());
m.state.energy=config.energyCapacity-1;
assert(m.cancelProduction(factory.id,replacement.id).ok,'Renamed projects can cancel older saved jobs');
assert.equal(m.state.energy,config.energyCapacity,'Refund respects capacity');
assert.equal(m.entity(factory.id).queue.length,0);
console.log(JSON.stringify({lastMatching:true,partialRefund:true,noDuplicateRefund:true,ownership:true,renamedSavedProject:true,capacity:true}));
