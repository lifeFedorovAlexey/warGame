import assert from 'node:assert/strict';
import fs from 'node:fs';
import {Mission} from '../campaign/mission.js';
import {contactRockAt,kickContactRock} from '../campaign/vehicle-contact-rock.js';
const config=JSON.parse(fs.readFileSync('assets/campaign/alpha/mission01/gameplay.json'));
const field={extent:4096,half:2048,cellMetres:32,heightAt:()=>0,gradientAt:()=>({x:0,y:0}),gridToWorld:([x,y])=>({x:x*32-2048,y:2048-y*32}),worldToGrid:(x,y)=>[(x+2048)/32,(2048-y)/32]};
const m=new Mission(config,field);m.state.units=[];m.state.buildings=[];m.state.camps=[];m.state.bounds=[0,0,127,127];m.rebuildNavigation();
const u=m.addUnit('bukhanka','rai',{x:0,y:0}),before={x:u.x,y:u.y,hp:u.hp};
kickContactRock(u,[1,0,0],1,0);
assert(contactRockAt(u,.1).roll>0);assert.equal(contactRockAt(u,.1).pitch,0);
assert(contactRockAt(u,.4).roll<0,'The suspension swings back');
const first=contactRockAt(u,.2);kickContactRock(u,[-1,0,0],1,.2);
assert(Math.abs(contactRockAt(u,.2).roll-first.roll)<1e-10,'A second contact changes velocity without snapping the angle');
assert.deepEqual(contactRockAt(u,3),{roll:0,pitch:0,rollSpeed:0,pitchSpeed:0});
assert.deepEqual({x:u.x,y:u.y,hp:u.hp},before,'Visual response never pushes a car or removes HP');
for(const [key,value] of Object.entries(contactRockAt(u,.4)))assert(Math.abs(contactRockAt(JSON.parse(JSON.stringify(u)),.4)[key]-value)<1e-10,'Save/load keeps the same suspension phase');
// A real swept, low-energy contact: the second car entered the old route.
delete u.contactRock;u.x=-16.6;u.previousX=u.x;u.heading=-Math.PI/2;u.driveSpeed=9;u.reversing=false;
u.path=[{x:40,y:0}];u.task={type:'move',x:40,y:0};
const parked=m.addUnit('bukhanka','rai',{x:0,y:0});
m.move(u,.1);
if(process.argv.includes('--diagnose'))console.log(JSON.stringify({u,parked,pairs:[...(m.collisionPairs??[])]}));
assert(u.contactRock&&parked.contactRock,'Low-energy contact reaches the production feedback hook');
assert.equal(u.hp,u.maxHp);assert.equal(parked.hp,parked.maxHp);assert.equal(parked.x,0);assert.equal(parked.y,0,'The struck vehicle is not repelled');
const saved=u.contactRock;m.vehicleCollision(u,9,new Set([parked]));assert.equal(u.contactRock,saved,'Continuous touching does not pump the suspension each frame');
m.state.time=.1;m.vehicleCollision(u,24,new Set([parked]));assert(parked.hp<parked.maxHp,'A light touch must not suppress the next damaging impact');
const savedMission=m.save(),phaseBefore=contactRockAt(parked,.2);m.state.time=100;m.contactRockPairs.set([u.id,parked.id].sort().join('|'),100);
m.load(savedMission);assert.equal(m.contactRockPairs.size,0,'Loading an earlier save clears future contact cooldowns');
const loaded=m.state.units.find(unit=>unit.id===parked.id);
assert.deepEqual(contactRockAt(loaded,.2),phaseBefore,'Mission save/load keeps the visual suspension state');
const slow=new Mission(config,field);slow.state.units=[];slow.state.buildings=[];slow.state.camps=[];slow.state.bounds=[0,0,127,127];slow.rebuildNavigation();
const slowCar=slow.addUnit('bukhanka','rai',{x:-16.6,y:0},{heading:-Math.PI/2}),slowParked=slow.addUnit('bukhanka','rai',{x:0,y:0});
slowCar.driveSpeed=7;slowCar.reversing=false;slowCar.path=[{x:40,y:0}];slowCar.task={type:'move',x:40,y:0};slow.move(slowCar,.1);
assert(slowParked.contactRock,'Low-speed failure reports the visual contact separately');
assert(slowCar.driveWatch.blocked>0,'Suspension feedback must not reset the blocked movement timer');
assert.equal(slowCar.x,-16.6);assert.equal(slowCar.hp,320);assert.equal(slowParked.hp,320);
console.log(JSON.stringify({passed:true,physicalContact:true,parkedRock:contactRockAt(parked,.1),hp:[u.hp,parked.hp]}));
