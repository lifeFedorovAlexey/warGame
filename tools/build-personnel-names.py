"""Build an offline name catalog from the downloaded, attributed dictionaries."""
import csv
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools/.runtime-names'))
import duckdb

src = ROOT / 'references/personnel/names'
out = ROOT / 'assets/campaign/personnel'
docs = ROOT / 'docs/campaign/personnel'
out.mkdir(parents=True, exist_ok=True)
docs.mkdir(parents=True, exist_ok=True)
normalize = lambda text: text.strip().casefold().replace('ё', 'е')
frequencies = {}
for count, name, gender in duckdb.connect().execute(
    'SELECT count, text, gender FROM read_parquet(?)', [str(src / 'registry-names.parquet')]).fetchall():
    key = normalize(name)
    frequencies[key] = frequencies.get(key, 0) + max(0, count or 0)
names = {}
for row in json.loads((src / 'nen-names.json').read_text(encoding='utf-8')):
    name = row['name'].strip()
    if not re.fullmatch(r'[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?', name):
        continue
    key = normalize(name)
    if key in names:
        if names[key]['gender'] != row['gender']:
            names[key]['gender'] = 'u'
        continue
    names[key] = {'name': name, 'gender': row['gender'], 'origin': row['origin'],
        'sampleCount': frequencies.get(key), 'sourceUrl': row['url']}
entries = sorted(names.values(), key=lambda r: (-(r['sampleCount'] or 0), normalize(r['name'])))
rank, previous = 0, None
for i, row in enumerate(entries):
    count = row['sampleCount']
    if count != previous:
        rank = i + 1
    row['frequencyRank'] = rank if count else None
    # Missing observations receive only a small gameplay fallback weight.
    # It is not a fabricated demographic count or rank.
    row['selectionWeight'] = max(1, count or 0)
    previous = count
catalog = {'version': 1, 'retrievedOn': '2026-11-10',
    'frequencyBasis': 'Observed name counts in the RussianNames public-register sample published in 2019; not a 2026 population census or a worldwide frequency estimate.',
    'unrankedPolicy': 'No observed count: frequencyRank=null; alphabetical after observed names.',
    'attributions': [
        {'title': 'Данные: НЭН — сервис «Имена»', 'url': 'https://n-e-n.ru/imena/', 'license': 'CC-BY-4.0'},
        {'title': 'RussianNames / Ivan Begtin, public-register frequency sample', 'url': 'https://github.com/datacoon/russiannames', 'license': 'BSD-3-Clause (repository); CC-BY-SA (ODSS data catalog)'},
    ],
    'sourceSha256': {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in [src/'nen-names.json', src/'registry-names.parquet']},
    'entries': entries}
(out/'names.js').write_text('// Generated by tools/build-personnel-names.py. See names-data.md for sources and licenses.\nexport default '+json.dumps(catalog, ensure_ascii=False, separators=(',', ':'))+';\n', encoding='utf-8')
with (docs/'names-ranked.csv').open('w', encoding='utf-8-sig', newline='') as f:
    writer = csv.writer(f, delimiter=';')
    writer.writerow(['Ранг в выборке', 'Имя', 'Встречаемость в выборке', 'Пол', 'Происхождение'])
    for row in entries:
        writer.writerow([row['frequencyRank'] or '', row['name'], row['sampleCount'] or '', row['gender'], row['origin']])
(docs/'names-ranked.txt').write_text('Имена по наблюдаемой частоте в выборке открытых реестров RussianNames (2019).\nЭто не мировая перепись и не частоты населения за 2026 год.\nДля имён без наблюдений ранг не выдумывается.\nДанные: НЭН — сервис «Имена», https://n-e-n.ru/imena/; RussianNames, https://github.com/datacoon/russiannames\n\n'+'\n'.join(f"{r['frequencyRank'] or '—'}. {r['name']} — {r['sampleCount'] if r['sampleCount'] else 'нет данных'}" for r in entries)+'\n', encoding='utf-8-sig')
print(json.dumps({'names': len(entries), 'ranked': sum(r['frequencyRank'] is not None for r in entries), 'top': entries[:5]}, ensure_ascii=True))
