import fs from 'node:fs';

// Read alpha only: PNG files remain untouched. Coordinates let CSS display each
// complete subject even when generated sheets have uneven gutters.
export async function measureUiAtlases(page) {
  await page.goto('http://127.0.0.1:8766/assets/ui/README.md');
  const regions = await page.evaluate(async () => {
    const {iconGroups} = await import('/assets/ui/icons.js');
    function split(counts, cells) {
      const size=counts.length, cuts=[0], step=size/cells;
      for(let cell=1;cell<cells;cell++) {
        const target=cell*step, lo=Math.floor(target-step*.42), hi=Math.ceil(target+step*.42), gaps=[];
        for(let start=lo;start<hi;start++) {
          if(counts[start])continue;
          let end=start+1;while(end<hi&&!counts[end])end++;
          gaps.push({start,end});start=end;
        }
        gaps.sort((a,b)=>(b.end-b.start)-(a.end-a.start)||Math.abs((a.start+a.end)/2-target)-Math.abs((b.start+b.end)/2-target));
        if(!gaps.length)throw new Error('No transparent gutter at '+target);
        cuts.push(Math.floor((gaps[0].start+gaps[0].end)/2));
      }
      cuts.push(size);return cuts;
    }
    const result={};
    for(const {file} of iconGroups) {
      const image=new Image();image.src='/assets/ui/'+file+'.png';await image.decode();
      const width=image.naturalWidth,height=image.naturalHeight,canvas=document.createElement('canvas');
      canvas.width=width;canvas.height=height;
      const context=canvas.getContext('2d',{willReadFrequently:true});context.drawImage(image,0,0);
      const pixels=context.getImageData(0,0,width,height).data;
      const opaque=(x,y)=>pixels[(y*width+x)*4+3]>32;
      const rowCounts=new Uint32Array(height);
      for(let y=0;y<height;y++)for(let x=0;x<width;x++)if(opaque(x,y))rowCounts[y]++;
      const rowCuts=split(rowCounts,5),rects=[];
      for(let row=0;row<5;row++) {
        const top=rowCuts[row],bottom=rowCuts[row+1],columnCounts=new Uint32Array(width);
        for(let y=top;y<bottom;y++)for(let x=0;x<width;x++)if(opaque(x,y))columnCounts[x]++;
        const columns=split(columnCounts,4);
        for(let column=0;column<4;column++) {
          let left=width,right=0,upper=height,lower=0;
          for(let y=top;y<bottom;y++)for(let x=columns[column];x<columns[column+1];x++)if(opaque(x,y)) {
            left=Math.min(left,x);right=Math.max(right,x);upper=Math.min(upper,y);lower=Math.max(lower,y);
          }
          if(right<=left||lower<=upper)throw new Error('Empty cell: '+file+' '+row+' '+column);
          // Four source pixels retain antialiased edges and soft internal detail.
          const x=Math.max(columns[column],left-4),y=Math.max(top,upper-4);
          rects.push([x,y,Math.min(columns[column+1],right+5)-x,Math.min(bottom,lower+5)-y]);
        }
      }
      result[file]={width,height,rects};
    }
    return result;
  });
  fs.writeFileSync('assets/ui/atlas-regions.js', '// Measured alpha bounds; generated by check-ui-icons.mjs --measure-atlases.\nexport const atlasRegions = '+JSON.stringify(regions,null,2)+';\n');
  console.log(JSON.stringify(Object.fromEntries(Object.entries(regions).map(([file,data])=>[file,{width:data.width,height:data.height,cells:data.rects.length}]))));
}
