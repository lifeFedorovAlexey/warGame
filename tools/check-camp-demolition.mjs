import assert from 'node:assert/strict';
import fs from 'node:fs';
import {Mission} from '../campaign/mission.js';
import {isCampPerimeter} from '../campaign/camp-demolition.js';
import {automaticCombatTarget} from '../campaign/combat-policy.js';
import {updateWrecks} from '../campaign/wreck-lifecycle.js';
const config=JSON.parse(fs.readFileSync('assets/campaign/alpha/mission01/gameplay.json'));
const field={extent:4096,half:2048,cellMetres:32,heightAt:()=>0,gradientAt:()=>({x:0,y:0}),gridToWorld:([x,y])=>({x:x*32-2048,y:2048-y*32}),worldToGrid:(x,y)=>[(x+2048)/32,(2048-y)/32]};
function fixture(){
 const m=new Mission(config,field);m.state.units=[];m.state.buildings=[];
 m.state.camps=[{id:'a',x:0,y:0,gate:{x:0,y:70},baseVersion:1,artifact:'flamethrower'},{id:'b',x:240,y:0,gate:{x:240,y:70},baseVersion:1}];
 m.state.flags={lastRevealed:true,raidWon:true};m.state.bounds=[0,0,127,127];m.state.pendingCinematics=[];m.state.artifacts=[];
 m.visible.fill(255);m.explored.fill(255);
 const add=(kind,campId,x,y,extra={})=>m.addStructure(kind,'scavs',{x,y},{campId,...extra});
 const core=add('camp-core','a',0,0),store=add('scav-store','a',40,0,{campInfrastructure:true}),tower=add('mg-tower','a',-40,0);
 const walls=Array.from({length:6},(_,i)=>add(i===5?'scav-gate':'scav-fence','a',-60+i*24,65,{campInfrastructure:true}));
 const other=add('camp-core','b',240,0),otherWall=add('scav-fence','b',240,65,{campInfrastructure:true});
 const orphan=add('scav-fence',undefined,320,65),friendly=add('scav-fence','a',360,65,{owner:'rai',completed:true});
 const guard=m.addUnit('raider','scavs',{x:90,y:100},{campId:'a'}),player=m.addUnit('builder','rai',{x:-200,y:0});
 m.rebuildNavigation();m.drainEffects();m.drainEvents();
 return {m,core,store,tower,walls,other,otherWall,orphan,friendly,guard,player};
}
const f=fixture(),{m,core,store,tower,walls,otherWall,orphan,friendly,guard}=f;
const wallIds=walls.map(b=>b.id),untouched=[otherWall,orphan,friendly].map(b=>[b.id,b.hp]);
const kill=b=>m.damage(b,b.hp);
kill(core);kill(tower);m.updateMission();
assert(walls.every(b=>b.hp>0&&b.campDemolitionAt===undefined),'Storage is still a building even if marked infrastructure');
assert(!m.state.camps[0].cleared);
// Automatic fire must finish a remaining warehouse instead of ignoring it.
const gun=m.addUnit('bukhanka','rai',{x:40,y:-60});
assert.equal(automaticCombatTarget(m,gun,m.unitSpec(gun))?.id,store.id);
kill(store);m.drainEffects();m.drainEvents();m.updateMission();
assert(walls.some(b=>b.hp<=0)&&walls.some(b=>b.hp>0),'Perimeter collapses in a short chain');
assert(walls.filter(b=>b.hp>0).every(b=>Number.isFinite(b.campDemolitionAt)));
assert(guard.hp>0&&!m.state.camps[0].cleared,'Surviving troops do not prevent perimeter demolition');
const deadlines=walls.map(b=>[b.id,b.campDemolitionAt]);
const firstExplosions=m.drainEffects().filter(e=>e.type==='explosion').map(e=>e.targetId);
const destroyedBefore=m.state.statistics.enemiesDestroyed;
m.load(m.save());
assert.deepEqual(m.state.buildings.filter(b=>wallIds.includes(b.id)).map(b=>[b.id,b.campDemolitionAt]),deadlines,'Reload preserves demolition timing');
m.state.time+=.5;m.updateMission();
const effects=m.drainEffects().filter(e=>e.type==='explosion').map(e=>e.targetId);
assert.deepEqual(new Set([...firstExplosions,...effects]),new Set(wallIds),'Every segment and gate gets its ordinary explosion');
assert.equal(firstExplosions.length+effects.length,wallIds.length,'No duplicate explosions after load');
assert(m.state.buildings.filter(b=>wallIds.includes(b.id)).every(b=>b.hp===0&&b.damage.wreck&&b.removeAt>b.destroyedAt));
assert.equal(m.state.statistics.enemiesDestroyed,destroyedBefore+wallIds.length-firstExplosions.length);
assert.deepEqual(untouched.map(([id])=>[id,m.entity(id).hp]),untouched,'Neighbouring, unassigned and player-owned fences are untouched');
assert(m.entity(guard.id));assert(!m.state.camps[0].cleared);
m.damage(m.entity(guard.id),m.entity(guard.id).hp);m.updateMission();
assert(m.state.camps[0].cleared);assert.equal(m.state.artifacts.filter(a=>a.key==='flamethrower').length,1);
m.drainEffects();m.updateMission();assert.equal(m.drainEffects().length,0);
m.state.time+=7;updateWrecks(m);assert(!m.state.buildings.some(b=>wallIds.includes(b.id)),'The collapsed fence leaves the navigation obstacle set');
// Old cleared camps with their buildings already removed still clean up once.
const legacy=fixture();legacy.m.state.camps[0].cleared=true;
legacy.m.state.buildings=legacy.m.state.buildings.filter(b=>b.campId!=='a'||isCampPerimeter(b));
legacy.m.updateMission();legacy.m.state.time+=1;legacy.m.updateMission();
assert(legacy.walls.every(b=>b.hp===0));assert(legacy.otherWall.hp>0);
const warehouse=fixture();
for(const target of [warehouse.core,warehouse.tower,warehouse.guard])warehouse.m.damage(target,target.hp);
warehouse.m.updateMission();
assert(!warehouse.m.state.camps[0].cleared,'A warehouse alone still prevents mission credit for clearing the camp');
assert(warehouse.walls.every(b=>b.hp>0));
warehouse.m.damage(warehouse.store,warehouse.store.hp);warehouse.m.updateMission();
assert(warehouse.m.state.camps[0].cleared,'Fence segments do not delay clearing the camp');
console.log('PASS: last building incl. storage/tower, living troops, camp isolation, gates, normal explosions/wrecks, one-shot cleanup, mid-chain saves and old cleared saves');
