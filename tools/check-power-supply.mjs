import assert from 'node:assert/strict';
import fs from 'node:fs';
import {Mission} from '../campaign/mission.js';
import {oilPowerStatus} from '../campaign/oil-economy.js';
import {createHeightfield} from '../demo/map-route.js';
const json=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const config=json('assets/campaign/alpha/mission01/gameplay.json');
const field=createHeightfield(json('assets/maps/alpha/heightfield.json'));
const mission=new Mission(config,field),point=field.gridToWorld(config.startGrid);
mission.updateEconomy(0);assert.equal(mission.state.powered,false);
const station=mission.addStructure('generator','rai',point);
mission.updateEconomy(0);assert.equal(mission.state.powered,false);
station.completed=true;mission.updateEconomy(1);
assert.equal(mission.state.powered,true,'A completed nuclear station needs no oil to run');
assert.equal(mission.state.energyRate,0);assert.equal(mission.state.oilLinked,0);
assert.deepEqual(oilPowerStatus(mission.state,config),{stations:1,wells:0,capacity:4,connected:0,unpowered:0,perStation:4});
const wells=config.oilFields.map(grid=>mission.addStructure('derrick','rai',field.gridToWorld(grid),{completed:true}));
mission.updateEconomy(1);
assert.equal(mission.state.oilLinked,4);assert.equal(wells[4].powered,false);
assert.equal(mission.state.energyRate,4*config.buildings.derrick.energyPerSecond);
assert.equal(wells[4].pumpTime??0,0,'An unpowered well does not pump oil');
assert.deepEqual(oilPowerStatus(mission.state,config),{stations:1,wells:5,capacity:4,connected:4,unpowered:1,perStation:4});
const second=mission.addStructure('generator','rai',{x:point.x+100,y:point.y});
mission.updateEconomy(1);assert.equal(mission.state.oilLinked,4);
second.completed=true;mission.updateEconomy(1);assert.equal(mission.state.oilLinked,5);
assert.equal(mission.state.energyRate,5*config.buildings.derrick.energyPerSecond);
assert.equal(oilPowerStatus(mission.state,config).capacity,8);
station.hp=0;mission.updateEconomy(1);assert.equal(mission.state.oilLinked,4);
second.hp=0;mission.updateEconomy(1);assert.equal(mission.state.powered,false);assert.equal(mission.state.oilLinked,0);
assert(wells.every(w=>!w.powered));
assert.equal(oilPowerStatus(mission.state,config).capacity,0);
// Factories and laboratories spend oil when ordered; they do not consume
// power capacity or burn the stored resource during prepaid work.
const unpaidStock=mission.state.energy;
const lab=mission.addStructure('lab','rai',{x:point.x+100,y:point.y+100},{completed:true});
const researchKey=Object.keys(config.research)[0];lab.research={key:researchKey,progress:0};
const idleFactory=mission.addStructure('factory','rai',{x:point.x-100,y:point.y-100},{completed:true});
idleFactory.queue.push({kind:'bukhanka',progress:0});
mission.updateEconomy(2);
assert.equal(mission.state.energy,unpaidStock,'No factory/laboratory upkeep is subtracted from oil');
assert.equal(mission.state.energyRate,0);
assert.equal(lab.research.progress,2/config.research[researchKey].seconds);
assert.equal(idleFactory.queue[0].progress,2/config.units.bukhanka.seconds);
assert.equal(oilPowerStatus(mission.state,config).capacity,0,'Other buildings do not supply power');
station.hp=station.maxHp;for(const well of wells)well.hp=0;
const factory=mission.addStructure('factory','rai',{x:point.x,y:point.y-100},{completed:true});
factory.queue.push({kind:'bukhanka',progress:0});mission.updateEconomy(1);
assert.equal(mission.state.powered,true);assert(factory.queue[0].progress>0,'The factory can use reserve resources without oil production');
assert.equal(mission.state.oilLinked,0);
const saved=JSON.parse(mission.save());saved.state.powered=false;
const restored=new Mission(config,field);restored.load(JSON.stringify(saved));
assert(restored.state.powered,'Old saves recalculate the nuclear supply');
assert.equal(restored.state.energy,saved.state.energy,'The legacy save balance remains oil');
const ignored=[{kind:'generator',owner:'scavs',hp:950,completed:true},{kind:'generator',owner:'rai',hp:950,completed:false},{kind:'derrick',owner:'rai',hp:0,completed:true}];
assert.deepEqual(oilPowerStatus({buildings:ignored},config),{stations:0,wells:0,capacity:0,connected:0,unpowered:0,perStation:4});
console.log('PASS: oil income, four wells per NPP, overload, completed/living/friendly counts, prepaid factory/research without power or upkeep, legacy saves');
