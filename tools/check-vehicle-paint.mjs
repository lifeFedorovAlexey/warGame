import assert from 'node:assert/strict';
import fs from 'node:fs';
import {registerHooks} from 'node:module';
import * as T from '../demo/vendor/three.module.js';
import {Mission} from '../campaign/mission.js';
import {createHeightfield} from '../demo/map-route.js';
import {VEHICLE_PAINTS,vehiclePaint,vehiclePaintTint,paintVehicleModel} from '../campaign/vehicle-paint.js';
import {projectAssemblyKey} from '../campaign/vehicle-designs.js';
import {createDamageDebris} from '../campaign/damage-debris.js';
import {prepareDamageGeometry} from '../campaign/damage-geometry.js';
