def inflect(phrases):
    for phrase in phrases.values():
        text = phrase['text']; female = text
        for male, fem in {**COMPOUNDS, **FIRST_PERSON}.items():
            if re.match(re.escape(male) + r'(?=$|[\s.,!?])', female):
                female = fem + female[len(male):]
                break
        if female != text:
            phrase.update(femaleText=female, femaleTextBase=text)
        elif phrase.get('femaleTextBase') != text:
            phrase.pop('femaleText', None); phrase.pop('femaleTextBase', None)


def review(rules, phrases):
    changes = {}
    active = {n['phraseId'] for r in rules if r['enabled'] and r['support']=='wired'
              for tier in r['tiers'] for g in tier['graphs'] for n in g['nodes']}
    def change(key, text):
        old = phrases[key]['text']
        if old != text:
            changes.setdefault(key, {'before':old})['after'] = text
            phrases[key]['text'] = text
    for key in active:
        text = phrases[key]['text']
        if text in REPLACEMENTS:
            change(key, REPLACEMENTS[text])
    for rule in rules:
        if not rule['enabled'] or rule['support']!='wired': continue
        for tier in rule['tiers']:
            prefix = rule['id']+'.'+tier['id']+'.'
            for graph in tier['graphs']:
                suffix = graph['id'].removeprefix(prefix)
                lines = DIALOGUES.get(rule['id']+'.'+suffix)
                if lines:
                    assert len(lines)==len(graph['nodes']), graph['id']
                    for node, text in zip(graph['nodes'], lines): change(node['phraseId'], text)
    return changes
