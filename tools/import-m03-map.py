"""Offline import of Warzone 2100 Alpha 3. Embed 44 x 93 without stretching."""
import json,struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'references/terrain/alpha/original-sub1-1'
OUT=ROOT/'assets/campaign/alpha/mission03'
def objects(name):
    b=(SRC/name).read_bytes();version,count=struct.unpack_from('<II',b,4)
    assert version==8
    stride=(len(b)-12)//count
    result=[]
    for i in range(count):
        r=b[12+i*stride:12+(i+1)*stride]
        ident,x,y,z,rotation,owner=struct.unpack_from('<6I',r,40)
        result.append(dict(id=ident,kind=r[:40].split(b'\0')[0].decode(),grid=[x/128,y/128],rotation=rotation,owner=owner))
    return result
b=(SRC/'game.map').read_bytes();version,w,h=struct.unpack_from('<III',b,4)
assert (version,w,h)==(10,44,93)
tiles=[struct.unpack_from('<HB',b,16+i*3) for i in range(w*h)]
t=(SRC/'ttypes.ttp').read_bytes();types=struct.unpack_from('<'+str((len(t)-12)//2)+'H',t,12)
ground_lines=(SRC/'visual-source/arizonaground.txt').read_text(encoding='utf-8').splitlines()[1:]
grounds=['a_water','a_cliff','a_concrete','a_mud','a_green','a_red','a_yellow','a_sand']
data=dict(source='Warzone 2100 / Alpha 3 / sub1-1',width=w,height=h,offset=[42,17],cellMetres=32,heightUnitMetres=.5,
          groundCorners=[[grounds.index(v) for v in line.split(',')] for line in ground_lines],
          heights=[v[1] for v in tiles],tiles=[v[0] for v in tiles],terrainTypes=[types[v[0]&511] for v in tiles],
          labels=json.loads((SRC/'labels.json').read_text()),structures=objects('struct.bjo'),features=objects('feat.bjo'),units=objects('dinit.bjo'))
OUT.mkdir(parents=True,exist_ok=True)
(OUT/'original-map.js').write_text('// Generated by tools/import-m03-map.py; provenance: references/terrain/alpha/original-sub1-1.\nexport default '+json.dumps(data,separators=(',',':'))+';\n',encoding='utf-8')
print(f'Imported {w} x {h} original heights, {len(data["features"])} features, {len(data["units"])} guards; no stretching or rotation.')
